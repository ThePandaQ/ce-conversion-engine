<#
.SYNOPSIS
    Install pdfconv - an offline, open-source PDF conversion CLI - on this PC.

.DESCRIPTION
    - Creates a dedicated Python virtual environment (default: %LOCALAPPDATA%\PDFConv\venv)
    - Installs open-source dependencies (PyMuPDF, pypdf, pdfplumber, pdf2docx,
      python-docx, python-pptx, openpyxl, Pillow, RapidOCR)
    - Copies pdfconv.py into the install dir and generates a small pdfconv.cmd launcher
    - Appends the install dir to the *User* PATH (idempotent; preserves existing entries)
    - Runs a self-check (doctor)

    This script is intentionally ASCII-only so it parses correctly in both
    Windows PowerShell 5.1 and PowerShell 7+.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\install.ps1

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\install.ps1 -InstallDir "D:\Tools\PDFConv" -SkipDeps -NoPath
#>
param(
    [string]$InstallDir = "$env:LOCALAPPDATA\PDFConv",
    [switch]$SkipDeps,
    [switch]$NoPath,
    [switch]$NoDesktopShortcut
)
$ErrorActionPreference = "Stop"
try { $env:PYTHONIOENCODING = "utf-8"; [Console]::OutputEncoding = [System.Text.Encoding]::UTF8 } catch {}
$srcDir = Split-Path -Parent $PSCommandPath
$python = (Get-Command python -ErrorAction SilentlyContinue).Source
if (-not $python) {
    throw "python was not found in PATH. Install Python 3.10+ first."
}

Write-Host "== pdfconv install ==" -ForegroundColor Cyan
Write-Host "Install dir: $InstallDir"
Write-Host "Python:      $python"

New-Item -ItemType Directory -Force -Path "$InstallDir\app", "$InstallDir\logs" | Out-Null

$venvPy = "$InstallDir\venv\Scripts\python.exe"
if (-not (Test-Path $venvPy)) {
    Write-Host "[1/5] Creating venv ..."
    & $python -m venv "$InstallDir\venv"
    if ($LASTEXITCODE -ne 0) { throw "venv creation failed" }
} else {
    Write-Host "[1/5] venv already exists, skipping"
}

if (-not $SkipDeps) {
    Write-Host "[2/5] Installing dependencies (first run may take 1-3 minutes) ..."
    & $venvPy -m pip install --upgrade pip | Out-Null
    & $venvPy -m pip install pymupdf pypdf pdfplumber pdf2docx python-docx python-pptx openpyxl pillow pefile easyofd pywin32
    if ($LASTEXITCODE -ne 0) { throw "core dependency install failed (see $InstallDir\logs)" }
    # OCR is optional: a failure here must not block the install.
    & $venvPy -m pip install rapidocr_onnxruntime | Tee-Object -FilePath "$InstallDir\logs\pip-ocr.log"
    if ($LASTEXITCODE -ne 0) {
        Write-Warning "RapidOCR install failed: OCR features will be unavailable, other features are fine."
    }
    & $venvPy -m pip freeze | Out-File -Encoding utf8 "$InstallDir\logs\pip-freeze.txt"
} else {
    Write-Host "[2/5] -SkipDeps: dependency install skipped"
}

Write-Host "[3/5] Copying program files ..."
Copy-Item "$srcDir\pdfconv.py" "$InstallDir\app\pdfconv.py" -Force
Copy-Item "$srcDir\README.md" "$InstallDir\app\README.md" -Force -ErrorAction SilentlyContinue
Copy-Item "$srcDir\VERSION" "$InstallDir\app\VERSION" -Force -ErrorAction SilentlyContinue

Write-Host "[4/5] Generating launcher ..."
# Build the .cmd with explicit CRLF and ASCII only; use %~dp0 so the
# launcher works even when the user profile path contains non-ASCII chars.
$nl = [char]13 + [char]10
$cmd = "@echo off" + $nl +
       "chcp 65001 >nul" + $nl +
       "rem pdfconv launcher generated by install.ps1 (ASCII, CRLF)" + $nl +
       "`"%~dp0venv\Scripts\python.exe`" `"%~dp0app\pdfconv.py`" %*" + $nl
[System.IO.File]::WriteAllText("$InstallDir\pdfconv.cmd", $cmd, [System.Text.Encoding]::ASCII)

if (-not $NoPath) {
    Write-Host "[5/5] Updating User PATH ..."
    $userPath = [Environment]::GetEnvironmentVariable("Path", "User")
    $parts = @()
    if ($userPath) { $parts = $userPath.Split(";") | Where-Object { $_ -and $_.Trim() } }
    if ($parts -contains $InstallDir) {
        Write-Host "      already present, skipping"
    } else {
        $newPath = ($parts + $InstallDir) -join ";"
        [Environment]::SetEnvironmentVariable("Path", $newPath, "User")
        Write-Host "      appended: $InstallDir"
    }
} else {
    Write-Host "[5/5] -NoPath: PATH update skipped"
}

# Best effort: tell Explorer that the environment changed so newly opened
# terminals pick up the updated PATH without a logout.
try {
    Add-Type -Namespace PdfConvWin32 -Name NativeMethods -MemberDefinition @'
[DllImport("user32.dll", SetLastError = true, CharSet = CharSet.Auto)]
public static extern IntPtr SendMessageTimeout(IntPtr hWnd, uint Msg, UIntPtr wParam, string lParam, uint fuFlags, uint uTimeout, out UIntPtr lpdwResult);
'@ -ErrorAction SilentlyContinue
    $HWND_BROADCAST = [IntPtr]0xffff
    $WM_SETTINGCHANGE = 0x001A
    $res = [UIntPtr]::Zero
    [PdfConvWin32.NativeMethods]::SendMessageTimeout($HWND_BROADCAST, $WM_SETTINGCHANGE, [UIntPtr]::Zero, "Environment", 2, 3000, [ref]$res) | Out-Null
} catch {
    # non-fatal: user may need to open a new terminal or re-login
}

Write-Host "[6/6] Desktop shortcut / GUI launcher ..."
Copy-Item "$srcDir\desktop\pdfconv-launcher.ps1" "$InstallDir\app\pdfconv-launcher.ps1" -Force
if (Test-Path "$srcDir\desktop\background.jpg") {
    Copy-Item "$srcDir\desktop\background.jpg" "$InstallDir\app\background.jpg" -Force
}
$ico = "$InstallDir\app\ce.ico"
if (-not (Test-Path $ico) -and (Test-Path "$srcDir\desktop\make_icon.py")) {
    & $venvPy "$srcDir\desktop\make_icon.py" $ico | Out-Null
}
if (Test-Path "$srcDir\desktop\ce.ico") {
    Copy-Item "$srcDir\desktop\ce.ico" $ico -Force
}
# Keep the legacy icon as a fallback.
if (Test-Path "$srcDir\desktop\pdfconv.ico") {
    Copy-Item "$srcDir\desktop\pdfconv.ico" "$InstallDir\app\pdfconv.ico" -Force
}
if (-not $NoDesktopShortcut) {
    $shortcutScript = "$srcDir\desktop\create-shortcut.ps1"
    if (Test-Path $shortcutScript) {
        try {
            & $shortcutScript -InstallDir $InstallDir
        } catch {
            Write-Warning "desktop shortcut creation failed: $($_.Exception.Message)"
        }
    } else {
        Write-Warning "create-shortcut.ps1 not found; skipping shortcut"
    }
} else {
    Write-Host "      -NoDesktopShortcut: shortcut skipped"
}

Write-Host "== self check ==" -ForegroundColor Cyan
& $venvPy "$InstallDir\app\pdfconv.py" doctor
Write-Host ""
Write-Host "Install complete." -ForegroundColor Green
Write-Host "Open a new terminal and run:      pdfconv doctor" -ForegroundColor Green
Write-Host "(If the current terminal cannot find 'pdfconv', open a new one or re-login once;"
Write-Host " the launcher can also be called directly as: $InstallDir\pdfconv.cmd)"
Write-Host "Or in this terminal:              `"$InstallDir\pdfconv.cmd`" doctor"
Write-Host "Example:                          `"$InstallDir\pdfconv.cmd`" pdf2png `"$srcDir\tests\wps-print-template.pdf`" --dpi 120"
